# --- помощники форматирования ---
FONT = "Times New Roman"


def _run_fmt(r, size=14, bold=False, italic=False):
    r.font.name = FONT
    r._r.get_or_add_rPr().get_or_add_rFonts().set(qn("w:eastAsia"), FONT)
    r.font.size = Pt(size)
    r.bold = bold
    r.italic = italic


def para(text="", size=14, bold=False, italic=False, align="both", indent=True, after=8, line=1.5):
    p = d.add_paragraph()
    pf = p.paragraph_format
    pf.space_after = Pt(after)
    pf.line_spacing = line
    if indent:
        pf.first_line_indent = Cm(1.25)
    p.alignment = {"both": WD_ALIGN_PARAGRAPH.JUSTIFY, "center": WD_ALIGN_PARAGRAPH.CENTER,
                   "left": WD_ALIGN_PARAGRAPH.LEFT}[align]
    if text:
        _run_fmt(p.add_run(text), size, bold, italic)
    return p


def formula(text):
    return para(text, size=14, italic=True, align="center", indent=False, after=4)


def heading(text, level=1):
    p = d.add_paragraph()
    ps_el = OxmlElement("w:pStyle")
    ps_el.set(qn("w:val"), f"Heading{level}")
    p._p.get_or_add_pPr().insert(0, ps_el)
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(8)
    r = p.add_run(text)
    _run_fmt(r, 16 if level == 1 else 14, bold=True)
    r.font.color.rgb = docx.shared.RGBColor(0, 0, 0)
    return p


def page_break():
    d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


fig_no = [0]


def figure(fname, caption, width=15.5):
    p = para(align="center", indent=False, after=2, line=1.0)
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(os.path.join(IMG, fname), width=Cm(width))
    fig_no[0] += 1
    para(f"Рис. {fig_no[0]}. {caption}", size=12, align="center", indent=False, after=10, line=1.0)


def toc():
    p = para("Оглавление", size=16, bold=True, align="center", indent=False)
    p = d.add_paragraph()
    r = p.add_run()
    for tag, attr in (("w:fldChar", {"w:fldCharType": "begin"}),
                      ("w:instrText", None),
                      ("w:fldChar", {"w:fldCharType": "separate"})):
        el = OxmlElement(tag)
        if attr:
            for k, v in attr.items():
                el.set(qn(k), v)
        else:
            el.set(qn("xml:space"), "preserve")
            el.text = 'TOC \\o "1-2" \\h \\z \\u'
        r._r.append(el)
    r2 = p.add_run("Нажмите правой кнопкой → «Обновить поле», чтобы построить оглавление.")
    _run_fmt(r2, 12, italic=True)
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")
    p.add_run()._r.append(end)
    # попросить Word обновить поля при открытии
    settings = d.settings.element
    uf = OxmlElement("w:updateFields")
    uf.set(qn("w:val"), "true")
    settings.append(uf)


